  <h3 class="text-xs font-semibold text-slate-500 dark:text-slate-400 uppercase tracking-wider mb-2">
    Sobre o programa
  </h3>
  <p>
    O <strong>Minhas Vantagens</strong> é o programa de relacionamento do Itaú
    que recompensa clientes dos segmentos
    <strong>Uniclass</strong> e <strong>Personnalité</strong> com benefícios
    exclusivos. A cada produto ou serviço utilizado — como investimentos,
    gastos no cartão de crédito, seguros, consórcios e financiamentos — o
    cliente acumula <strong>passos</strong>, que determinam seu nível dentro
    do programa.
  </p>
  <p class="mt-2">
    Cada segmento possui regras próprias de acúmulo e uma tabela de níveis
    distinta: o <strong>Uniclass</strong> vai do Nível 1 ao 5, com faixas que
    começam em 0, 4, 10, 16 e 30 passos; o <strong>Personnalité</strong>
    também possui cinco níveis, mas com faixas mais amplas (0, 4, 12, 20 e
    44 passos). Conforme o nível sobe, novos benefícios são liberados e os
    anteriores se acumulam, com algumas substituições — por exemplo, o
    valor de um cupom ou a duração de uma assinatura aumentam de acordo com
    o nível.
  </p>
  <p class="mt-2">
    Esta ferramenta permite simular seu perfil, comparar os dois segmentos
    lado a lado e descobrir quais produtos podem ajudar você a alcançar o
    próximo nível.
  </p>
</section>